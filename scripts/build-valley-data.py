# Builds js/data/valley-data.js from the Theban Mapping Project survey data (js/data/kv-raw.json)
# and AWS Terrain Tiles (SRTM) elevation tiles. Run from the project root:
#   python3 scripts/build-valley-data.py <folder with terrarium tiles 14_x_y.png>
# The survey grid is rotated 27.5 degrees from true north and shifted, as fitted to the elevation data
# and checked against published tomb coordinates; positions and bearings are converted to true ones.
import json, math, re, sys, struct, base64
from PIL import Image

ROT, DE, DN, DEM_OFFSET = -27.5, 165.0, 155.0, -2.4      # fitted: rotation (deg), shift (m), DEM minus survey (m)
LAT0, LON0, E0, N0, EL0 = 25.740389, 32.601417, 94069.638, 99572.277, 170.55
MLAT, MLON = 110850, 111320 * math.cos(math.radians(LAT0))
c, s = math.cos(math.radians(ROT)), math.sin(math.radians(ROT))

tiles = {}
for x in (9675, 9676):
    for y in (6978, 6979):
        tiles[(x, y)] = Image.open(f'{sys.argv[1]}/14_{x}_{y}.png').convert('RGB').load()
def dem(lat, lon):
    n = 2 ** 14; fx = (lon + 180) / 360 * n
    fy = (1 - math.log(math.tan(math.radians(lat)) + 1 / math.cos(math.radians(lat))) / math.pi) / 2 * n
    px, py = fx * 256 - 0.5, fy * 256 - 0.5; x0, y0 = math.floor(px), math.floor(py); tx, ty = px - x0, py - y0
    def H(ix, iy):
        r, g, b = tiles[(ix // 256, iy // 256)][ix % 256, iy % 256]; return r * 256 + g + b / 256 - 32768
    return (H(x0, y0) * (1 - tx) + H(x0 + 1, y0) * tx) * (1 - ty) + (H(x0, y0 + 1) * (1 - tx) + H(x0 + 1, y0 + 1) * tx) * ty
def true_xz(E, N):            # survey grid -> model metres (x east, z south), origin at the entrance of KV 62
    e, n = E - E0, N - N0
    return e * c - n * s, -(e * s + n * c)
def latlon(x, z): return LAT0 + (-z + DN) / MLAT, LON0 + (x + DE) / MLON
def ground(x, z): return dem(*latlon(x, z)) - DEM_OFFSET - EL0

kv = json.load(open('js/data/kv-raw.json'))
NAMES = {'/tombs/unknown-0': 12, '/node/5740': 32, '/tombs/unknown': 56}
tombs = []
for k in kv:
    m = re.search(r'kv-(\d+)', k['slug']); num = int(m.group(1)) if m else NAMES.get(k['slug'], k['slug'].split('-')[-2].upper() if 'kv-' in k['slug'] else None)
    if k['slug'] == '/tombs/kv-unknown': num = 'A'
    if k['slug'] == '/tombs/kv-f-unknown': num = 'F'
    t = {'kv': num, 'title': k['title'].replace('&#039;', "'"), 'len': k.get('len'), 'area': k.get('area'), 'maxH': k.get('maxH'),
         'owner': k.get('ownerType'), 'entrance': k.get('entranceLoc'), 'disc': k.get('disc'), 'els': k.get('els', [])}
    if k.get('E'):
        x, z = true_xz(k['E'], k['N']); t['pos'] = [round(x, 2), round(k['elev'] - EL0, 2), round(z, 2)]
        t['elev'] = k['elev']
    tombs.append(t)

# Terrain: an 8 m grid, nudged near each surveyed entrance so the ground meets it (the satellite heights are ~30 m resolution)
located = [t for t in tombs if 'pos' in t]
xs = [t['pos'][0] for t in located]; zs = [t['pos'][2] for t in located]
X0, X1, Z0, Z1, STEP = min(xs) - 420, max(xs) + 420, min(zs) - 420, max(zs) + 420, 8
nx, nz = int((X1 - X0) / STEP) + 1, int((Z1 - Z0) / STEP) + 1
fix = [(t['pos'][0], t['pos'][2], t['pos'][1] - ground(t['pos'][0], t['pos'][2])) for t in located]
vals = []
for j in range(nz):
    z = Z0 + j * STEP
    for i in range(nx):
        x = X0 + i * STEP
        h = ground(x, z)
        wsum = 0; corr = 0
        for fx, fz, d in fix:
            w = math.exp(-((x - fx) ** 2 + (z - fz) ** 2) / (2 * 30 ** 2)); wsum += w; corr += w * d
        if wsum > 1e-3: h += corr / max(1, wsum)
        vals.append(max(-32000, min(32000, round(h * 10))))
raw = struct.pack('<%dh' % len(vals), *vals)
meta = {'x0': X0, 'z0': Z0, 'step': STEP, 'nx': nx, 'nz': nz, 'scale': 0.1, 'lat0': LAT0 + DN / MLAT, 'lon0': LON0 + DE / MLON, 'bearingFix': -ROT}
out = ('// The Valley of the Kings: every tomb in the Theban Mapping Project survey, and the ground around them.\n'
       '// Generated by scripts/build-valley-data.py. Positions are metres from the entrance of KV 62 (x east, y up, z south),\n'
       '// converted from the survey grid, which runs 27.5 degrees off true north. Ground heights come from AWS Terrain Tiles\n'
       '// (SRTM, about 30 m detail), adjusted near each entrance to meet its surveyed height. Rows run north to south.\n'
       'export const VALLEY = %s;\nexport const TOMBS = %s;\nexport const DEM_DATA = \'%s\';\n'
       % (json.dumps(meta), json.dumps(tombs, ensure_ascii=False, separators=(',', ':')), base64.b64encode(raw).decode()))
open('js/data/valley-data.js', 'w').write(out)
print('tombs', len(tombs), 'located', len(located), 'grid', nx, nz, 'KB', len(out) // 1024)
for t in located:
    if t['kv'] in (62, 17): print(t['kv'], t['pos'])
